import { chromium } from '@playwright/test';
const OUT = 'prototype/adaptive-vocab/screenshots';
const browser = await chromium.launch();
const errors = [];
const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
page.on('pageerror', (e) => errors.push('pageerror: ' + e.message));
page.on('console', (m) => { if (m.type() === 'error') errors.push('console: ' + m.text()); });
await page.goto('http://127.0.0.1:4174/prototype/adaptive-vocab/', { waitUntil: 'networkidle' });
await page.waitForTimeout(4500);
console.log('screen:', await page.locator('#screen-status').textContent());
console.log('metrics:', await page.locator('#s-mae-current').textContent(), await page.locator('#s-mae-hybrid').textContent(), await page.locator('#s-precision').textContent());
await page.screenshot({ path: `${OUT}/after-screen-1440.png`, fullPage: true });
await page.screenshot({ path: `${OUT}/after-screen-1440-top.png`, fullPage: false });
await page.locator('#tab-btn-review').click();
await page.waitForTimeout(3500);
await page.locator('#audit-run').click();
await page.waitForTimeout(4000);
console.log('review:', await page.locator('#review-status').textContent());
console.log('audit:', await page.locator('#audit-status').textContent());
await page.screenshot({ path: `${OUT}/after-review-1440.png`, fullPage: true });
await page.locator('[data-truemodel="exponential"]').click();
await page.waitForTimeout(3500);
console.log('exp review:', await page.locator('#review-status').textContent());
console.log('exp retention:', await page.locator('#r-retention-fsrs').textContent());
await page.screenshot({ path: `${OUT}/after-review-exponential-1440.png`, fullPage: true });
await page.locator('#tab-btn-formula').click();
await page.waitForTimeout(300);
await page.evaluate(() => window.scrollTo(0, 0));
await page.screenshot({ path: `${OUT}/after-formula-1440.png`, fullPage: true });

const mobile = await browser.newPage({ viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true, deviceScaleFactor: 1 });
mobile.on('pageerror', (e) => errors.push('mobile pageerror: ' + e.message));
await mobile.goto('http://127.0.0.1:4174/prototype/adaptive-vocab/', { waitUntil: 'networkidle' });
await mobile.waitForTimeout(4500);
const overflow = await mobile.evaluate(() => document.documentElement.scrollWidth - document.documentElement.clientWidth);
console.log('mobile overflow:', overflow);
await mobile.screenshot({ path: `${OUT}/after-screen-390.png`, fullPage: true });
await mobile.locator('#tab-btn-review').click();
await mobile.waitForTimeout(3500);
await mobile.screenshot({ path: `${OUT}/after-review-390.png`, fullPage: true });
console.log('errors:', errors);
await browser.close();
